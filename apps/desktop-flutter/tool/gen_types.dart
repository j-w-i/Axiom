late Map<String, Object?> defs;
final out = StringBuffer();

void main(List<String> args) {
  final schema = jsonDecode(File(_schemaPath).readAsStringSync()) as Map<String, Object?>;
  defs = (schema[r'$defs'] as Map).cast<String, Object?>();
  out.writeln('// GENERATED by tool/gen_types.dart from schemas/ipc/protocol.schema.json.');
  out.writeln('// Do not edit: change crates/protocol, run');
  out.writeln('//   cargo run -p axiom-protocol --example export_schema');
  out.writeln('// then `dart run tool/gen_types.dart`. check.sh fails when this file is stale.');
  out.writeln(
    '// ignore_for_file: constant_identifier_names, prefer_single_quotes, use_null_aware_elements, prefer_if_null_operators',
  );
  out.writeln();
  out.writeln("import 'protocol_runtime.dart';");
  out.writeln();
  out.writeln("const protocolVersion = '${schema['protocolVersion']}';");
  out.writeln();
  final names = defs.keys.toList()..sort();
  for (final name in names) {
    if (_skip.contains(name)) continue;
    _definition(name, defs[name]! as Map<String, Object?>);
  }
  _catalogue(schema);
  final file = File(_outPath);
  if (args.contains('--check')) {
    // Compare formatted output: write to a temporary file, format it, compare.
    // Inside the package, so the formatter uses analysis_options.yaml's page width.
    final tmp = File('${Directory('.dart_tool').createTempSync('gen').path}/protocol.g.dart')
      ..writeAsStringSync(out.toString());
    Process.runSync('dart', ['format', tmp.path]);
    final text = tmp.readAsStringSync();
    tmp.parent.deleteSync(recursive: true);
    if (!file.existsSync() || file.readAsStringSync() != text) {
      stderr.writeln('$_outPath is stale: run `dart run tool/gen_types.dart`.');
      exit(1);
    }
    return;
  }
  file.writeAsStringSync(out.toString());
  Process.runSync('dart', ['format', _outPath]);
  stdout.writeln('wrote $_outPath (${names.length} definitions)');
}

String typeName(String def) => _rename[def] ?? def;

String refName(String ref) => typeName(ref.split('/').last);

String fieldName(String wire) {
  var n = wire.replaceAll(RegExp(r'[^A-Za-z0-9_]'), '_');
  if (RegExp(r'^[0-9]').hasMatch(n)) n = 'v$n';
  if (n.startsWith('_')) n = 'x$n';
  return _reserved.contains(n) ? '${n}_' : n;
}

String enumValue(String wire) {
  final parts = wire.split(RegExp(r'[^A-Za-z0-9]+')).where((p) => p.isNotEmpty).toList();
  if (parts.isEmpty) return 'empty';
  var n = parts.first[0].toLowerCase() + parts.first.substring(1);
  for (final p in parts.skip(1)) {
    n += p[0].toUpperCase() + p.substring(1);
  }
  if (RegExp(r'^[0-9]').hasMatch(n)) n = 'v$n';
  return _reserved.contains(n) ? '${n}_' : n;
}

String pascal(String wire) {
  final v = enumValue(wire).replaceAll(RegExp(r'_$'), '');
  return v[0].toUpperCase() + v.substring(1);
}

String _dartString(String s) =>
    "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'";

/// The string values of a string-enum schema, or null when it is not one.
List<String>? stringValues(Map<String, Object?> s) {
  if (s['enum'] is List && (s['type'] == 'string' || s['type'] == null)) {
    return (s['enum']! as List).cast<String>();
  }
  if (s['const'] is String) return [s['const']! as String];
  final one = s['oneOf'] ?? s['anyOf'];
  if (one is List && one.isNotEmpty) {
    final all = <String>[];
    for (final v in one) {
      final vs = stringValues((v as Map).cast<String, Object?>());
      if (vs == null) return null;
      all.addAll(vs);
    }
    return all;
  }
  return null;
}

void _doc(Map<String, Object?> s, String indent) {
  final d = s['description'];
  if (d is! String || d.isEmpty) return;
  for (final line in d.trim().split('\n')) {
    out.writeln('$indent/// ${line.trimRight()}'.trimRight());
  }
}

void _definition(String name, Map<String, Object?> s) {
  final n = typeName(name);
  final values = stringValues(s);
  if (values != null && (s['type'] == 'string' || s['oneOf'] != null || s['enum'] != null)) {
    _enum(n, s, values);
    return;
  }
  if (s['type'] == 'string') {
    _doc(s, '');
    out.writeln('typedef $n = String;');
    out.writeln();
    return;
  }
  final one = s['oneOf'];
  if (one is List) {
    _union(n, s, one.map((v) => (v as Map).cast<String, Object?>()).toList());
    return;
  }
  if (s['type'] == 'object' || s['properties'] != null) {
    _class(n, s, null);
    return;
  }
  _doc(s, '');
  out.writeln('typedef $n = Object?;');
  out.writeln();
}

void _enum(String n, Map<String, Object?> s, List<String> values) {
  _doc(s, '');
  out.writeln('enum $n {');
  for (final v in values) {
    out.writeln('  ${enumValue(v)}(${_dartString(v)}),');
  }
  out.writeln('  ;');
  out.writeln();
  out.writeln('  const $n(this.wire);');
  out.writeln('  final String wire;');
  out.writeln();
  out.writeln('  static $n fromJson(Object? json) =>');
  out.writeln(
    "      values.firstWhere((v) => v.wire == json, orElse: () => throw FormatException('$n: \$json'));",
  );
  out.writeln();
  out.writeln('  String toJson() => wire;');
  out.writeln('}');
  out.writeln();
}

/// The const tag property shared by every variant (`type` or `kind`), if any.
String? _tagOf(List<Map<String, Object?>> variants) {
  for (final tag in ['type', 'kind']) {
    if (variants.every((v) {
      final p = (v['properties'] as Map?)?[tag];
      return p is Map && p['const'] is String;
    })) {
      return tag;
    }
  }
  return null;
}

void _union(String n, Map<String, Object?> s, List<Map<String, Object?>> variants) {
  final tag = _tagOf(variants);
  final keyed =
      tag == null &&
      variants.every((v) => (v['required'] as List?)?.length == 1 && v['properties'] is Map);
  if (tag == null && !keyed) {
    _doc(s, '');
    out.writeln('typedef $n = Object?;');
    out.writeln();
    return;
  }
  _doc(s, '');
  out.writeln('sealed class $n implements Wire {');
  out.writeln('  const $n();');
  out.writeln();
  out.writeln('  static $n fromJson(Object? json) {');
  out.writeln('    final m = asMap(json);');
  if (tag != null) {
    out.writeln("    switch (m['$tag']) {");
    for (final v in variants) {
      final value = ((v['properties']! as Map)[tag] as Map)['const']! as String;
      out.writeln('      case ${_dartString(value)}:');
      out.writeln('        return $n${pascal(value)}.fromJson(m);');
    }
    out.writeln('    }');
    out.writeln("    throw FormatException('$n: unknown $tag \${m['$tag']}');");
  } else {
    for (final v in variants) {
      final key = (v['required']! as List).first as String;
      out.writeln(
        '    if (m.containsKey(${_dartString(key)})) return $n${pascal(key)}.fromJson(m);',
      );
    }
    out.writeln("    throw FormatException('$n: \$json');");
  }
  out.writeln('  }');
  out.writeln();
  out.writeln('  @override');
  out.writeln('  Map<String, Object?> toJson();');
  out.writeln('}');
  out.writeln();
  for (final v in variants) {
    final suffix = tag != null
        ? pascal(((v['properties']! as Map)[tag] as Map)['const']! as String)
        : pascal((v['required']! as List).first as String);
    _class('$n$suffix', v, (base: n, tag: tag));
  }
}

class _Field {
  _Field(this.wire, this.type, this.required, this.decode, this.encode, this.schema);
  final String wire;
  final String type; // Dart type without the nullable mark
  final bool required;
  final String Function(String expr) decode;
  final String Function(String expr) encode;
  final Map<String, Object?> schema;
  String get name => fieldName(wire);
  String get dartType => required ? type : '$type?';
}

/// (type, decode, encode, nullable) for a property schema.
({String type, String Function(String) decode, String Function(String) encode, bool nullable})
_typeOf(Object? schema) {
  if (schema is! Map) {
    return (type: 'Object?', decode: (e) => e, encode: (e) => e, nullable: false);
  }
  final s = schema.cast<String, Object?>();
  final ref = s[r'$ref'];
  if (ref is String) {
    final target = defs[ref.split('/').last]! as Map<String, Object?>;
    final rn = refName(ref);
    if (target['type'] == 'string' && stringValues(target) == null) {
      return (type: rn, decode: (e) => '$e as String', encode: (e) => e, nullable: false);
    }
    final isOpen =
        target['type'] == null &&
        target['oneOf'] == null &&
        target['enum'] == null &&
        target['properties'] == null;
    if (isOpen) return (type: 'Object?', decode: (e) => e, encode: (e) => e, nullable: false);
    return (
      type: rn,
      decode: (e) => '$rn.fromJson($e)',
      encode: (e) => '$e.toJson()',
      nullable: false,
    );
  }
  final any = s['anyOf'];
  if (any is List) {
    final nonNull = any.where((x) => !(x is Map && x['type'] == 'null')).toList();
    if (nonNull.length == 1) {
      final t = _typeOf(nonNull.first);
      return (type: t.type, decode: t.decode, encode: t.encode, nullable: true);
    }
    return (type: 'Object?', decode: (e) => e, encode: (e) => e, nullable: false);
  }
  var type = s['type'];
  var nullable = false;
  if (type is List) {
    nullable = type.contains('null');
    final rest = type.where((t) => t != 'null').toList();
    type = rest.length == 1 ? rest.first : null;
  }
  switch (type) {
    case 'string':
      return (type: 'String', decode: (e) => '$e as String', encode: (e) => e, nullable: nullable);
    case 'integer':
      return (
        type: 'int',
        decode: (e) => '($e as num).toInt()',
        encode: (e) => e,
        nullable: nullable,
      );
    case 'number':
      return (
        type: 'double',
        decode: (e) => '($e as num).toDouble()',
        encode: (e) => e,
        nullable: nullable,
      );
    case 'boolean':
      return (type: 'bool', decode: (e) => '$e as bool', encode: (e) => e, nullable: nullable);
    case 'array':
      final items = s['items'] ?? ((s['prefixItems'] as List?)?.first);
      final it = _typeOf(items);
      final itType = it.nullable ? '${it.type}?' : it.type;
      final itDecode = it.nullable && it.type != 'Object?'
          ? (String x) => '$x == null ? null : ${it.decode(x)}'
          : it.decode;
      final itEncode = it.nullable && it.type != 'Object?'
          ? (String x) => '$x == null ? null : ${it.encode('$x!')}'
          : it.encode;
      return (
        type: 'List<$itType>',
        decode: (e) => '[for (final x in asList($e)) ${itDecode('x')}]',
        encode: (e) => itEncode('x') == 'x' ? e : '[for (final x in $e) ${itEncode('x')}]',
        nullable: nullable,
      );
    case 'object':
      final addl = s['additionalProperties'];
      if (addl != null) {
        final vt = _typeOf(addl);
        final vType = vt.nullable ? '${vt.type}?' : vt.type;
        return (
          type: 'Map<String, $vType>',
          decode: (e) => '{for (final kv in asMap($e).entries) kv.key: ${vt.decode('kv.value')}}',
          encode: (e) => vt.encode('v') == 'v'
              ? e
              : '{for (final kv in $e.entries) kv.key: ${vt.encode('kv.value')}}',
          nullable: nullable,
        );
      }
      return (
        type: 'Map<String, Object?>',
        decode: (e) => 'asMap($e)',
        encode: (e) => e,
        nullable: nullable,
      );
  }
  return (type: 'Object?', decode: (e) => e, encode: (e) => e, nullable: false);
}

void _class(String n, Map<String, Object?> s, ({String base, String? tag})? union) {
  final props = ((s['properties'] as Map?) ?? {}).cast<String, Object?>();
  final req = ((s['required'] as List?) ?? []).cast<String>().toSet();
  final fields = <_Field>[];
  final wires = props.keys.toList()..sort();
  for (final wire in wires) {
    if (union?.tag == wire) continue;
    final t = _typeOf(props[wire]);
    final open = t.type == 'Object?';
    final required = req.contains(wire) && !t.nullable;
    fields.add(
      _Field(
        wire,
        open ? 'Object' : t.type,
        required && !open,
        t.decode,
        t.encode,
        props[wire] is Map ? (props[wire]! as Map).cast<String, Object?>() : const {},
      ),
    );
  }
  _doc(s, '');
  final ext = union == null ? ' implements Wire' : ' extends ${union.base}';
  out.writeln('final class $n$ext {');
  if (fields.isEmpty) {
    out.writeln('  const $n();');
  } else {
    out.writeln('  const $n({');
    for (final f in fields) {
      out.writeln('    ${f.required ? 'required ' : ''}this.${f.name},');
    }
    out.writeln('  });');
  }
  out.writeln();
  for (final f in fields) {
    _doc(f.schema, '  ');
    out.writeln('  final ${f.dartType} ${f.name};');
  }
  if (fields.isNotEmpty) out.writeln();
  out.writeln('  static $n fromJson(Object? json) {');
  out.writeln(fields.isEmpty ? '    asMap(json);' : '    final m = asMap(json);');
  out.writeln('    return $n(');
  for (final f in fields) {
    final get = "m['${f.wire}']";
    final value = f.type == 'Object' ? get : f.decode(get);
    out.writeln(
      f.required ? '      ${f.name}: $value,' : '      ${f.name}: $get == null ? null : $value,',
    );
  }
  out.writeln('    );');
  out.writeln('  }');
  out.writeln();
  out.writeln('  @override');
  out.writeln('  Map<String, Object?> toJson() => {');
  if (union?.tag != null) {
    final value = (((s['properties']! as Map)[union!.tag] as Map)['const'])! as String;
    out.writeln("        '${union.tag}': ${_dartString(value)},");
  }
  for (final f in fields) {
    final enc = f.type == 'Object' ? f.name : f.encode(f.required ? f.name : '${f.name}!');
    out.writeln(
      f.required
          ? "        '${f.wire}': $enc,"
          : "        if (${f.name} != null) '${f.wire}': $enc,",
    );
  }
  out.writeln('      };');
  out.writeln('}');
  out.writeln();
}

void _catalogue(Map<String, Object?> schema) {
  String ty(Object? s) {
    if (s is Map && s[r'$ref'] is String) {
      final name = (s[r'$ref'] as String).split('/').last;
      if (_skip.contains(name)) return 'Object?';
      final t = _typeOf(s);
      return t.type;
    }
    return 'Object?';
  }

  String dec(Object? s) {
    final t = ty(s);
    if (t == 'Object?') return '(j) => j';
    return '$t.fromJson';
  }

  out.writeln('/// Every method of the protocol: `client.call(Methods.fsReadFile, params)`.');
  out.writeln('abstract final class Methods {');
  final methods = (schema['methods']! as Map).cast<String, Object?>();
  for (final name in methods.keys.toList()..sort()) {
    final m = (methods[name]! as Map).cast<String, Object?>();
    final p = ty(m['params']);
    final r = ty(m['result']);
    out.writeln(
      '  static const ${_member(name)} = Method<$p, $r>(${_dartString(name)}, ${dec(m['result'])});',
    );
  }
  out.writeln('}');
  out.writeln();
  out.writeln('/// Every notification: `client.on(Notifications.taskOutput, (p) => …)`.');
  out.writeln('abstract final class Notifications {');
  final notes = (schema['notifications']! as Map).cast<String, Object?>();
  for (final name in notes.keys.toList()..sort()) {
    final m = (notes[name]! as Map).cast<String, Object?>();
    final p = ty(m['params']);
    out.writeln(
      '  static const ${_member(name)} = NotificationType<$p>(${_dartString(name)}, ${dec(m['params'])});',
    );
  }
  out.writeln('}');
}

String _member(String wire) {
  final v = enumValue(wire.replaceAll(r'$/', 'protocol/'));
  return v;
}
