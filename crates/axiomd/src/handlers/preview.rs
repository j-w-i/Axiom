//! `preview/*` (protocol 0.5, ADR-0019 §2; M5-PREVIEW-001): the workspace's Vite dev server run
//! as a task with Axiom's plugin injected through a generated config that imports the user's own
//! (their files are never edited). The URL comes from the server's output; the page's adapter
//! dials the inspection service with the preview's token.

use crate::app::App;
use crate::handlers::env::process_environment;
use crate::handlers::ui::notify_state;
use axiom_exec::{SpawnSpec, TaskEvent};
use axiom_protocol::lifecycle::Empty;
use axiom_protocol::preview::{
    ListResult, PreviewId, PreviewInfo, PreviewRef, PreviewState, StartParams,
};
use axiom_protocol::task::{Command, Exited, Output};
use axiom_protocol::workspace::WorkspaceRef;
use axiom_protocol::{ErrorKind, RpcError};
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::Arc;
use std::time::Duration;

/// The plugin and the adapter, shipped inside the daemon (written next to each generated
/// config).
const PLUGIN: &str = include_str!("../../../../inspectors/web/plugin.mjs");
const ADAPTER: &str = include_str!("../../../../inspectors/web/adapter.js");
/// How long the dev server may take to print its URL.
const URL_WAIT: Duration = Duration::from_secs(60);
const USER_CONFIGS: &[&str] = &[
    "vite.config.js",
    "vite.config.mjs",
    "vite.config.ts",
    "vite.config.mts",
    "vite.config.cjs",
    "vite.config.cts",
];

static NEXT: AtomicU64 = AtomicU64::new(1);

/// The first loopback URL in a line of the dev server's output (ANSI colours removed).
pub fn find_url(line: &str) -> Option<String> {
    let mut plain = String::with_capacity(line.len());
    let mut chars = line.chars().peekable();
    while let Some(c) = chars.next() {
        if c == '\u{1b}' {
            // CSI: ESC [ … final byte in @..~
            if chars.peek() == Some(&'[') {
                chars.next();
                for d in chars.by_ref() {
                    if ('@'..='~').contains(&d) {
                        break;
                    }
                }
            }
            continue;
        }
        plain.push(c);
    }
    for start in ["http://127.0.0.1:", "http://localhost:", "http://[::1]:"] {
        if let Some(i) = plain.find(start) {
            let url: String = plain[i..]
                .chars()
                .take_while(|c| !c.is_whitespace())
                .collect();
            let port_ok = url[start.len()..]
                .chars()
                .next()
                .is_some_and(|c| c.is_ascii_digit());
            if port_ok {
                return Some(url.replacen("localhost", "127.0.0.1", 1));
            }
        }
    }
    None
}

/// The generated config: the user's config (if any) with Axiom's plugin first, the server on
/// loopback, and nothing opened by Vite itself.
pub fn generated_config(plugin: &Path, user: Option<&Path>, endpoint: &str, token: &str) -> String {
    let url = |p: &Path| {
        let s = p.to_string_lossy().replace('\\', "/");
        let s = if s.starts_with('/') {
            s
        } else {
            format!("/{s}")
        };
        format!("file://{s}")
    };
    let user_import = match user {
        Some(u) => format!("import * as user from {};\n", serde_json::json!(url(u))),
        None => "const user = {};\n".to_string(),
    };
    format!(
        "// GENERATED by Axiom for a preview (ADR-0019 §2). The project's own config is imported, not\n\
         // edited; Axiom's plugin is added in front. Delete freely: it is written again on start.\n\
         import axiom from {plugin};\n\
         {user_import}\
         export default async (env) => {{\n\
         \x20 let base = user.default ?? {{}};\n\
         \x20 if (typeof base === \"function\") base = await base(env);\n\
         \x20 base = (await base) ?? {{}};\n\
         \x20 const plugins = [axiom({{ endpoint: {endpoint}, token: {token} }}), ...(base.plugins ?? [])];\n\
         \x20 const server = {{ ...(base.server ?? {{}}), host: \"127.0.0.1\", open: false }};\n\
         \x20 return {{ ...base, plugins, server }};\n\
         }};\n",
        plugin = serde_json::json!(url(plugin)),
        endpoint = serde_json::json!(endpoint),
        token = serde_json::json!(token),
    )
}

fn failed(message: &str, output: &str) -> RpcError {
    RpcError::new(ErrorKind::PreviewFailed, message)
        .with_details(serde_json::json!({ "output": output }))
}

pub async fn start(app: Arc<App>, p: StartParams) -> Result<PreviewInfo, RpcError> {
    let ws = app.workspaces.get(&p.workspace_id)?;
    let root = ws.root().to_path_buf();
    // One preview per workspace: a second start returns the running one.
    if let Some(running) = app
        .previews
        .of_workspace(&p.workspace_id)
        .into_iter()
        .find(|i| matches!(i.state, PreviewState::Ready | PreviewState::Starting))
    {
        return Ok(running);
    }
    let inspect = app.previews.service(&app).await.map_err(|e| {
        RpcError::new(
            ErrorKind::Io,
            format!("The inspection service could not start: {e}"),
        )
    })?;
    let id = PreviewId(format!("p{}", NEXT.fetch_add(1, Ordering::SeqCst)));
    let token = inspect
        .register(id.clone(), root.clone())
        .map_err(|e| RpcError::new(ErrorKind::Io, format!("No randomness for a token: {e}")))?;

    // The generated config, the plugin and the adapter, under the data directory.
    let dir = app.env.data_dir.join("previews").join(&id.0);
    let write = |dir: &Path| -> std::io::Result<PathBuf> {
        std::fs::create_dir_all(dir)?;
        std::fs::write(dir.join("plugin.mjs"), PLUGIN)?;
        std::fs::write(dir.join("adapter.js"), ADAPTER)?;
        let user = USER_CONFIGS
            .iter()
            .map(|n| root.join(n))
            .find(|p| p.is_file());
        let cfg = dir.join("vite.config.mjs");
        std::fs::write(
            &cfg,
            generated_config(
                &dir.join("plugin.mjs"),
                user.as_deref(),
                &inspect.endpoint(),
                &token,
            ),
        )?;
        Ok(cfg)
    };
    let cfg = write(&dir).map_err(|e| {
        inspect.unregister(&id);
        RpcError::new(
            ErrorKind::Io,
            format!("Could not write the preview's config: {e}"),
        )
    })?;
    let cfg_s = cfg.to_string_lossy().into_owned();
    let argv = match p.argv {
        Some(a) if !a.is_empty() => a,
        _ => {
            let vite = root.join("node_modules").join(".bin").join("vite");
            if vite.is_file() {
                vec![
                    vite.to_string_lossy().into_owned(),
                    "--config".into(),
                    cfg_s.clone(),
                ]
            } else {
                ["npm", "run", "dev", "--", "--config", &cfg_s]
                    .map(String::from)
                    .to_vec()
            }
        }
    };
    let mut env = process_environment(&app, &p.workspace_id).await?;
    env.insert("AXIOM_INSPECT_ENDPOINT".into(), inspect.endpoint());
    env.insert("AXIOM_INSPECT_TOKEN".into(), token.clone());
    env.insert("AXIOM_INSPECT_CONFIG".into(), cfg_s);
    env.insert("BROWSER".into(), "none".into());
    let spec = SpawnSpec {
        command: Command::Argv(argv),
        cwd: root,
        env,
        label: Some("Preview".into()),
    };
    let (task_id, mut rx) = match app.executor.start(p.workspace_id.clone(), spec).await {
        Ok(x) => x,
        Err(e) => {
            inspect.unregister(&id);
            return Err(e.into());
        }
    };
    let info = PreviewInfo {
        preview_id: id.clone(),
        workspace_id: p.workspace_id.clone(),
        state: PreviewState::Starting,
        url: None,
        task_id: Some(task_id),
        adapter: None,
        message: None,
        output: None,
    };
    app.previews.insert(info.clone());
    notify_state(&app, info).await;

    // The server's output: relayed to the workspace's clients, searched for the URL, kept for a
    // failure report; its end is the preview's end.
    let (url_tx, url_rx) = tokio::sync::oneshot::channel::<Result<String, String>>();
    // Detached: it lives as long as the server does.
    {
        let app = app.clone();
        let id = id.clone();
        let ws_id = p.workspace_id.clone();
        tokio::spawn(async move {
            let mut url_tx = Some(url_tx);
            let mut tail = String::new();
            while let Some(ev) = rx.recv().await {
                match ev {
                    TaskEvent::Output(o) => {
                        tail.push_str(&o.data);
                        if tail.len() > 8192 {
                            let cut = tail.len() - 8192;
                            let cut = (cut..tail.len())
                                .find(|i| tail.is_char_boundary(*i))
                                .unwrap_or(0);
                            tail.drain(..cut);
                        }
                        for line in o.data.lines() {
                            app.previews.record_output(&id, line);
                        }
                        if url_tx.is_some() {
                            if let Some(u) = o.data.lines().find_map(find_url) {
                                let _ = url_tx.take().map(|t| t.send(Ok(u)));
                            }
                        }
                        for c in app.clients_of(&ws_id) {
                            let _ = c.notify::<Output>(o.clone()).await;
                        }
                    }
                    TaskEvent::Exited(x) => {
                        for c in app.clients_of(&ws_id) {
                            let _ = c.notify::<Exited>(x.clone()).await;
                        }
                        if let Some(t) = url_tx.take() {
                            let _ = t.send(Err(tail.clone()));
                        }
                        let stopping = app
                            .previews
                            .get(&id)
                            .is_some_and(|i| i.state == PreviewState::Stopped);
                        if let Some(i) = app.previews.update(&id, |i| {
                            i.adapter = None;
                            if !stopping {
                                i.state = PreviewState::Failed;
                                i.message = Some(match x.status.exit_code {
                                    Some(c) => format!("The dev server exited (code {c})."),
                                    None => "The dev server stopped.".into(),
                                });
                                i.output = Some(last_lines(&tail, 20));
                            }
                        }) {
                            if !stopping {
                                notify_state(&app, i).await;
                            }
                        }
                        if let Some(s) = app.previews.inspect() {
                            s.unregister(&id);
                        }
                        break;
                    }
                }
            }
        });
    }

    let outcome = tokio::time::timeout(URL_WAIT, url_rx).await;
    match outcome {
        Ok(Ok(Ok(url))) => {
            let info = app
                .previews
                .update(&id, |i| {
                    i.state = PreviewState::Ready;
                    i.url = Some(url);
                })
                .ok_or_else(crate::app::internal)?;
            notify_state(&app, info.clone()).await;
            Ok(info)
        }
        Ok(Ok(Err(output))) => Err(failed(
            "The dev server exited before it printed its address.",
            &last_lines(&output, 20),
        )),
        Ok(Err(_)) => Err(crate::app::internal()),
        Err(_) => {
            let _ = stop(
                app.clone(),
                PreviewRef {
                    preview_id: id.clone(),
                },
            )
            .await;
            Err(failed("The dev server printed no address within 60 s.", ""))
        }
    }
}

fn last_lines(s: &str, n: usize) -> String {
    let lines: Vec<&str> = s.lines().collect();
    lines[lines.len().saturating_sub(n)..].join("\n")
}

pub async fn stop(app: Arc<App>, p: PreviewRef) -> Result<Empty, RpcError> {
    let info = app
        .previews
        .get(&p.preview_id)
        .ok_or_else(|| RpcError::new(ErrorKind::NotFound, "There is no such preview."))?;
    if info.state == PreviewState::Stopped {
        return Ok(Empty {});
    }
    let info = app
        .previews
        .update(&p.preview_id, |i| {
            i.state = PreviewState::Stopped;
            i.adapter = None;
        })
        .ok_or_else(crate::app::internal)?;
    if let Some(s) = app.previews.inspect() {
        s.unregister(&p.preview_id);
    }
    if let Some(t) = &info.task_id {
        let _ = app.executor.cancel(t).await;
    }
    notify_state(&app, info).await;
    Ok(Empty {})
}

pub async fn list(app: Arc<App>, p: WorkspaceRef) -> Result<ListResult, RpcError> {
    app.workspaces.get(&p.workspace_id)?;
    Ok(ListResult {
        previews: app.previews.of_workspace(&p.workspace_id),
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn urls_are_found_in_vite_output() {
        assert_eq!(
            find_url("  \u{1b}[32m➜\u{1b}[39m  \u{1b}[1mLocal\u{1b}[22m:   \u{1b}[36mhttp://localhost:\u{1b}[1m5173\u{1b}[22m/\u{1b}[39m"),
            Some("http://127.0.0.1:5173/".into())
        );
        assert_eq!(
            find_url("  ➜  Local:   http://127.0.0.1:5174/"),
            Some("http://127.0.0.1:5174/".into())
        );
        assert_eq!(find_url("  ➜  Network: use --host to expose"), None);
        assert_eq!(find_url("see http://localhost:abc"), None);
    }

    #[test]
    fn the_generated_config_imports_the_users_and_puts_the_plugin_first() {
        let c = generated_config(
            Path::new("/data/previews/p1/plugin.mjs"),
            Some(Path::new("/ws/vite.config.ts")),
            "ws://127.0.0.1:9/",
            "t\"k",
        );
        assert!(c.contains("import axiom from \"file:///data/previews/p1/plugin.mjs\";"));
        assert!(c.contains("import * as user from \"file:///ws/vite.config.ts\";"));
        assert!(c.contains("axiom({ endpoint: \"ws://127.0.0.1:9/\", token: \"t\\\"k\" })"));
        assert!(c.contains("...(base.plugins ?? [])"));
        let none = generated_config(Path::new("/d/plugin.mjs"), None, "e", "t");
        assert!(none.contains("const user = {};"));
    }
}
