// Generates lib/daemon/protocol.g.dart from schemas/ipc/protocol.schema.json, which is itself
// generated from crates/protocol (ADR-0005: the Rust crate is the single source of truth).
//
//   dart run tool/gen_types.dart          write the file
//   dart run tool/gen_types.dart --check  fail if the file is stale (scripts/check.sh)
//
// The schema's shapes (schemars output) map to Dart as follows:
// - an object definition → a class with final fields, `fromJson` and `toJson`;
// - a string enum (`enum`, or a `oneOf` of string `enum`/`const`) → a Dart enum with its wire
//   values;
// - a `oneOf` of objects sharing a `const` tag (`type` or `kind`) → a sealed class with one
//   subclass per tag value;
// - a `oneOf` of objects told apart by their single required key (`{argv}` / `{shell}`) → a
//   sealed class with one subclass per key;
// - a string alias (`WorkspaceId`) → a typedef of String;
// - anything open (`true`, no type) → `Object?` (raw JSON).
// The `methods` and `notifications` catalogues become typed descriptors the client calls with.

