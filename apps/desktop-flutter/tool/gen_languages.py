#!/usr/bin/env python3
"""Writes lib/editor/languages.g.dart: every grammar re_highlight ships, with its display name
and highlight.js aliases (M5.5-LANG-001, ADR-0021 §1). Run after changing re_highlight's version:

    python3 tool/gen_languages.py
"""
import os, re, sys, pathlib

here = pathlib.Path(__file__).resolve().parent.parent
lock = (here / 'pubspec.lock').read_text()
m = re.search(r're_highlight:\n(?:.*\n)*?\s+version: "([^"]+)"', lock)
version = m.group(1)
pub = pathlib.Path(os.environ.get('PUB_CACHE', pathlib.Path.home() / '.pub-cache'))
src = pub / 'hosted' / 'pub.dev' / f're_highlight-{version}' / 'lib' / 'languages'
if not src.is_dir():
    sys.exit(f'gen_languages: {src} not found (flutter pub get first)')

rows = []
for f in sorted(src.glob('*.dart')):
    if f.stem == 'all':
        continue
    text = f.read_text()
    var = re.search(r'^final (lang\w+) = Mode\(', text, re.M).group(1)
    name = re.search(r'^    name: "((?:[^"\\]|\\.)*)"', text, re.M)
    aliases = re.search(r'^    aliases: \[(.*?)\]', text, re.M | re.S)
    al = re.findall(r'"((?:[^"\\]|\\.)*)"', aliases.group(1)) if aliases else []
    rows.append((f.stem, var, name.group(1) if name else f.stem, al))

def q(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$') + "'"

out = ['// GENERATED by tool/gen_languages.py from re_highlight ' + version + ': do not edit.',
       '// ignore_for_file: directives_ordering', '',
       "import 'package:re_highlight/re_highlight.dart';"]
out += [f"import 'package:re_highlight/languages/{s}.dart';" for s, _, _, _ in rows]
out += ['', '/// A grammar re_highlight ships: its highlight.js name, display name, aliases, and a',
        '/// function that builds it (top-level finals are lazy: nothing is built until called).',
        'typedef Grammar = ({String hljs, String name, List<String> aliases, Mode Function() mode});',
        '', 'const grammarCount = ' + str(len(rows)) + ';', '',
        'final List<Grammar> grammars = [']
for s, v, n, al in rows:
    out.append(f"  (hljs: {q(s)}, name: {q(n)}, aliases: const [{', '.join(q(a) for a in al)}], mode: () => {v}),")
out += ['];', '']
(here / 'lib' / 'editor' / 'languages.g.dart').write_text('\n'.join(out))
print(f'wrote lib/editor/languages.g.dart ({len(rows)} grammars)')
