#!/usr/bin/env node
// Generates src/daemon/protocol.gen.ts from the committed JSON Schema
// (schemas/ipc/protocol.schema.json), which is itself generated from
// crates/protocol (ADR-0005: the Rust crate is the single source of truth).
//
//   node scripts/gen-types.mjs           write the file
//   node scripts/gen-types.mjs --check   fail if the file is stale (used by check.sh)
import { compile } from "json-schema-to-typescript";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, "..");
const repo = resolve(pkg, "../..");
const schemaPath = process.env.AXIOM_PROTOCOL_SCHEMA ?? join(repo, "schemas/ipc/protocol.schema.json");
const outPath = join(pkg, "src/daemon/protocol.gen.ts");

const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
// Only the named definitions: the method catalogue ($defs.envelope/methods/…)
// is a description of the protocol, not a set of types the UI imports.
// The root document has no properties of its own (it is a catalogue), so the
// generator is pointed at one synthetic object whose properties reference every
// definition; `declareExternallyReferenced` then emits one exported type per
// definition, which is what the UI imports.
const names = Object.keys(schema.$defs).sort();
const root = {
  type: "object",
  properties: Object.fromEntries(names.map((n) => [n, { $ref: `#/$defs/${n}` }])),
  $defs: schema.$defs,
};

const generated = await compile(root, "AxiomProtocolCatalogue", {
  bannerComment: [
    "/* eslint-disable */",
    "// GENERATED by scripts/gen-types.mjs from schemas/ipc/protocol.schema.json.",
    "// Do not edit: change crates/protocol, run",
    "//   cargo run -p axiom-protocol --example export_schema",
    "// then regenerate this file. `pnpm run check:types` fails when it is stale (ADR-0005).",
  ].join("\n"),
  style: { singleQuote: false, semi: true, printWidth: 110 },
  additionalProperties: false,
  declareExternallyReferenced: true,
});

// Drop the synthetic wrapper interface: only the named protocol types are useful.
const body = generated
  .replace(/export interface AxiomProtocolCatalogue \{[\s\S]*?\n\}\n/, "")
  .trim();

const out = `${body}\n`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outPath, "utf8");
  } catch {
    /* missing */
  }
  if (current !== out) {
    console.error("protocol.gen.ts is stale: run `pnpm run gen:types` (ADR-0005)");
    process.exit(1);
  }
  console.log("protocol.gen.ts is current");
} else {
  writeFileSync(outPath, out);
  console.log(`wrote ${outPath} (${out.length} bytes)`);
}
